let currentLang = "ru";
let koreanIntroFontPromise = null;

function t(k) { return translations[currentLang][k] || translations.ru[k] || k; }

function ensureKoreanIntroFontReady() {
  const root = document.documentElement;
  if (currentLang !== "ko") {
    root.classList.add("ko-intro-font-ready");
    return;
  }

  root.classList.remove("ko-intro-font-ready");
  if (!document.fonts?.load) {
    root.classList.add("ko-intro-font-ready");
    return;
  }

  koreanIntroFontPromise ||= document.fonts.load("700 1em 'Gowun Batang'", "예카테리나 & 승택");
  koreanIntroFontPromise
    .catch(() => {})
    .finally(() => root.classList.add("ko-intro-font-ready"));
}

function applyTranslations(lang) {
  currentLang = translations[lang] ? lang : "ru";
  document.documentElement.lang = currentLang;
  ensureKoreanIntroFontReady();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const value = t(key);
    if (key === "address") {
      el.innerHTML = String(value).replace(/\n/g, "<br>");
    } else if (key === "signature3") {
      el.innerHTML = String(value).replace(/^&/, '<span class="signatureAmp">&amp;</span>');
    } else {
      el.textContent = value;
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-lang-src]").forEach((el) => {
    const src = el.dataset[`src${currentLang.charAt(0).toUpperCase()}${currentLang.slice(1)}`];
    if (src) el.src = src;
    el.dataset.currentLang = currentLang;
  });
  document.querySelectorAll(".lang").forEach((button) => button.classList.toggle("active", button.dataset.lang === currentLang));
  const formLang = document.getElementById("formLang");
  if (formLang) formLang.value = currentLang;
  const openInvite = document.getElementById("openInvite");
  if (openInvite) openInvite.setAttribute("aria-label", t("open"));
  try { localStorage.setItem("inviteLang", currentLang); } catch (e) {}
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: currentLang } }));
}
